// CPU+XPU 异构调度中间件 —— 共享数据类型
//
// 本文档中的类型对应《详细设计文档（新）》§4/§7 提到的跨类传递数据结构。
// 设计原则：
//   - 只放"跨类传递"的纯数据类型（POD 风格），不放业务逻辑；
//   - 不放任何设计层属性（属性一律落在各自的类里）；
//   - 字段命名与详细设计文档保持一致。

#ifndef SCHED_COMMON_SCHEDTYPES_H
#define SCHED_COMMON_SCHEDTYPES_H

#include <cstdint>
#include <string>
#include <vector>

namespace sched {

// ---------------------------------------------------------------------------
// 任务请求：推理引擎经 UDS 提交的调度请求（详见 §4.1 UC1）
// ---------------------------------------------------------------------------
struct TaskRequest {
    // 推理引擎侧的请求标识，用于应答一一对应
    std::string requestId;
    // 任务负载特征（维度与模型契约 input_dim 对齐）
    std::vector<float> payload;
};

// ---------------------------------------------------------------------------
// 任务结果：一次推理调度的产出（详见 §4.1 UC1）
// ---------------------------------------------------------------------------
struct TaskResult {
    bool ok = false;
    std::string message;
    // 动作组执行结果，与下发动作严格对位
    std::vector<int> actions;
};

// ---------------------------------------------------------------------------
// 单设备状态：CPU / NPU 各自采集后返回（详见 §7.11 / §7.12）
// ---------------------------------------------------------------------------
struct DeviceInfo {
    // 设备标识："cpu" / "npu"
    std::string device;
    // 当前频率（Hz）
    int curFreq = 0;
    // 可用频率表（Hz）
    std::vector<int> freqTable;
    // 采集是否有效；false 表示读设备节点失败
    bool valid = false;
    // CPU 独有：利用率，值域 [0,1]；NPU 恒为 0
    double utilization = 0.0;
};

// ---------------------------------------------------------------------------
// 系统状态：systemManager 汇聚 CPU / NPU 后的结果（详见 §7.10）
// ---------------------------------------------------------------------------
struct SystemInfo {
    DeviceInfo cpu;
    DeviceInfo npu;
    // 系统级有效标志：任一路失败即为 false
    bool valid = false;
};

// ---------------------------------------------------------------------------
// 系统特征：Agent 侧用于馈入模型的归一化特征（详见 §7.6）
// ---------------------------------------------------------------------------
struct SystemFeature {
    double ucpu = 0.0;         // CPU 利用率 [0,1]
    double unpu[3] = {0, 0, 0}; // NPU 三维利用/负载分量
    int cpuFreqKHz = 0;        // CPU 当前频率（kHz）
    int npuFreqKHz = 0;        // NPU 当前频率（kHz）
    bool stale = false;        // 是否来自过期兜底快照
};

// ---------------------------------------------------------------------------
// 对外系统特征状态：schedManager::getFeature 的返回（详见 §7.5）
// ---------------------------------------------------------------------------
struct SystemFeaturedState {
    SystemFeature feature;
    // 当前所选模型名（单一事实源在 schedManager::model，此处为副本快照）
    std::string model;
};

// ---------------------------------------------------------------------------
// 决策：decisionMaker 推理产出（详见 §7.7）
// ---------------------------------------------------------------------------
struct Decision {
    // 动作组：每个元素为一个动作编号（对应契约 actions 映射）
    std::vector<int> actionIds;
    // 目标设备名，与 actionIds 严格对位
    std::vector<std::string> targets;
};

// ---------------------------------------------------------------------------
// 设备动作：下发给单个设备的动作（详见 §7.9 / §7.10 / §7.11）
// ---------------------------------------------------------------------------
struct DeviceAction {
    // 目标设备："cpu" / "npu"
    std::string target;
    // 目标频率（Hz）；<=0 表示不调频
    int freqHz = 0;
    // 目标批大小；<=0 表示不调批
    int batchSize = 0;
};

// ---------------------------------------------------------------------------
// 动作执行结果：与动作严格对位（详见 §7.8）
// ---------------------------------------------------------------------------
struct ExecResult {
    bool ok = false;
    std::string message;
    // 是否发生了夹取（频率越界被调整到最近合法档）
    bool adjusted = false;
};

} // namespace sched

#endif // SCHED_COMMON_SCHEDTYPES_H
